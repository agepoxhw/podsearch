#!/usr/bin/env python3
"""Run the required queries against the live API and write results/queries.md and results/raw.json.

The Label and Reason columns are left EMPTY on purpose: a human listens to each hit and fills them in.
Labels live in results/labels.json (written by `make label`, or read from rows you typed into queries.md) and are
keyed by query + episode + start second, so re-running keeps every label whose hit is still there.
Standard library only, so it runs on the host: `make eval`.
"""
import json
import re
import subprocess
import urllib.parse
import urllib.request
from datetime import date
from pathlib import Path

API = "http://localhost:8080"
QUERIES = ["Putin", "Ukraine", "Middle East", "Iran"]
K = 20
CONTEXT_K = 5            # how many below-threshold hits to show for context
OUT = Path("results")
ROW = re.compile(r"^\|\s*\d+\s*\|\s*(✓|✗)?\s*\|[^|]*\|[^|]*\|[^|]*\|[^|]*#t=(\d+),\d+\)\s*\|(.*)\|\s*$")


def get(path: str, **params) -> dict:
    with urllib.request.urlopen(f"{API}{path}?{urllib.parse.urlencode(params)}", timeout=30) as r:
        return json.load(r)


def mmss(s: float) -> str:
    return f"{int(s // 60)}:{int(s % 60):02d}"


def link(h: dict) -> str:
    return f"[play]({API}{urllib.parse.quote(h['audio_url'])}#t={int(h['start_s'])},{int(h['end_s'])})"


def label_key(query: str, hit: dict) -> str:
    return f"{query}|{hit['episode']}|{int(hit['start_s'])}"


def labels_from_markdown(text: str) -> dict:
    """Labels typed by hand into queries.md. Episode comes from the row, query from the nearest ## heading."""
    out, query = {}, ""
    for line in text.splitlines():
        if line.startswith("## "):
            query = line[3:].strip()
        m = ROW.match(line)
        if m and (m.group(1) or m.group(3).strip()):
            episode = line.split("|")[4].strip()
            out[f"{query}|{episode}|{m.group(2)}"] = {"label": m.group(1) or "", "reason": m.group(3).strip()}
    return out


def load_labels() -> dict:
    """labels.json wins over what is typed in queries.md, so the two never fight."""
    path, md = OUT / "labels.json", OUT / "queries.md"
    labels = labels_from_markdown(md.read_text()) if md.exists() else {}
    if path.exists():
        labels.update(json.loads(path.read_text()))
    return labels


def save_labels(labels: dict) -> None:
    OUT.mkdir(exist_ok=True)
    (OUT / "labels.json").write_text(json.dumps(labels, indent=2, ensure_ascii=False, sort_keys=True))


def run_query(q: str) -> dict:
    res = get("/search", q=q, k=K)
    # Debug view (no threshold, no hub filter): the best hits that fell below 0.20, for context only.
    everything = get("/search", q=q, k=50, below_threshold="true")["hits"]
    below = [h for h in everything if h["score"] < res["threshold"]][:CONTEXT_K]
    return {"query": q, "threshold": res["threshold"], "model": res["model"], "hits": res["hits"], "below_threshold": below}


def markdown(results: list[dict], commit: str, labels: dict) -> str:
    t = results[0]["threshold"]
    lines = ["# Query results", "",
             f"Generated by `make eval` on {date.today()} (commit {commit}). Threshold {t} (true cosine), k={K}, "
             f"10 s chunks, hub filter on, model `{results[0]['model']}`.", "",
             "**To do (human):** listen to each hit and mark it `✓` or `✗` with a one-line **Reason**, either on the "
             "page `make label` opens or by typing here. Labels are kept in `results/labels.json`; `make eval` keeps them.", ""]
    for r in results:
        lines += [f"## {r['query']}", "", f"{len(r['hits'])} hits at or above {t}.", "",
                  "| # | Label | Score | Episode | Time | Listen | Reason |", "|---|---|---|---|---|---|---|"]
        for i, h in enumerate(r["hits"], 1):
            lab = labels.get(label_key(r["query"], h), {})
            reason = lab.get("reason", "").replace("|", "/").replace("\n", " ")
            lines.append(f"| {i} | {lab.get('label', '')} | {h['score']:.3f} | {h['episode']} | "
                         f"{mmss(h['start_s'])}-{mmss(h['end_s'])} | {link(h)} | {reason} |")
        if r["below_threshold"]:
            lines += ["", f"Below threshold, for context only (not results, not labelled): " + ", ".join(
                f"{h['score']:.3f} {h['episode']} {mmss(h['start_s'])}" for h in r["below_threshold"])]
        lines.append("")
    return "\n".join(lines)


def main() -> None:
    labels = load_labels()
    commit = subprocess.run(["git", "rev-parse", "--short", "HEAD"], capture_output=True, text=True).stdout.strip() or "unknown"
    results = [run_query(q) for q in QUERIES]
    live = {label_key(r["query"], h) for r in results for h in r["hits"]}
    gone = [k for k in labels if k not in live]
    if gone:
        print(f"warning: {len(gone)} labels belong to hits that are no longer returned (kept in labels.json): {gone[:3]}...")
    OUT.mkdir(exist_ok=True)
    save_labels(labels)
    (OUT / "queries.md").write_text(markdown(results, commit, labels))
    (OUT / "raw.json").write_text(json.dumps({"commit": commit, "k": K, "results": results}, indent=2))
    for r in results:
        done = sum(1 for h in r["hits"] if labels.get(label_key(r["query"], h), {}).get("label"))
        print(f"{r['query']:12} {len(r['hits']):2} hits, {done} labelled, best {r['hits'][0]['score'] if r['hits'] else '-'}")
    print(f"wrote {OUT / 'queries.md'} and {OUT / 'raw.json'}")


if __name__ == "__main__":
    main()
